import assert from 'node:assert/strict'
import path from 'node:path'
import fs from 'node:fs/promises'
import os from 'node:os'
import { createServer } from 'vite'
import react from '@vitejs/plugin-react'
import { chromium } from 'playwright-core'

const repo = process.cwd(), temporary = await fs.mkdtemp(path.join(os.tmpdir(), 'javdex-tasks-ui-'))
let server, browser
try {
  server = await createServer({ configFile: false, root: path.join(repo, 'scripts/ui-regression'), cacheDir: path.join(temporary, 'vite'),
    plugins: [react()], resolve: { alias: { '@shared': path.join(repo, 'packages/contracts/src'), react: path.join(repo, 'node_modules/react'), 'react-dom': path.join(repo, 'node_modules/react-dom') } },
    server: { host: '127.0.0.1', port: 0, watch: null, fs: { allow: [repo] } } })
  await server.listen()
  browser = await chromium.launch({ ...(process.env.JAVDEX_BROWSER_EXECUTABLE ? { executablePath: process.env.JAVDEX_BROWSER_EXECUTABLE } : { channel: process.env.JAVDEX_BROWSER_CHANNEL || 'chrome' }), headless: true })
  for (const viewport of [{ width: 1600, height: 1000 }, { width: 1000, height: 640 }, { width: 800, height: 640 }]) for (const theme of ['slate', 'light']) {
    const page = await browser.newPage({ viewport, reducedMotion: 'reduce' }), errors = []
    page.on('pageerror', error => errors.push(error.message))
    await page.goto(`http://127.0.0.1:${server.httpServer.address().port}/task-center.html?theme=${theme}`)
    await page.getByText('3 项运行中 · 6 项需处理', { exact: true }).waitFor()
    assert.equal(await page.locator('[data-task-count]').textContent(), '6')
    assert.equal(await page.getByRole('progressbar', { name: '字幕生成进度' }).getAttribute('value'), '42')
    if (viewport.width === 1600 && theme === 'slate') await page.screenshot({ path: path.join(repo, 'out/task-center-overview.png') })
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false)
    const nav = page.getByRole('navigation', { name: '任务分类' })
    await nav.getByRole('link', { name: '刮削', exact: true }).click()
    await page.getByRole('button', { name: '暂停', exact: true }).click()
    await page.getByRole('button', { name: '继续', exact: true }).click()
    await page.getByRole('button', { name: '终止任务', exact: true }).click()
    assert.deepEqual(await page.evaluate(() => window.taskCommands), ['pause', 'resume'])
    await page.getByRole('button', { name: '返回', exact: true }).click()
    await page.evaluate(() => window.setBatchWithoutEvent('paused'))
    await page.getByRole('button', { name: '刷新任务', exact: true }).click()
    await page.getByRole('button', { name: '继续', exact: true }).waitFor()
    await page.evaluate(() => window.setBatchWithoutEvent('idle'))
    await page.getByRole('button', { name: '刷新任务', exact: true }).click()
    await page.getByText('暂无批量刮削任务', { exact: true }).waitFor()
    await nav.getByRole('link', { name: '扫描', exact: true }).click()
    await page.getByRole('button', { name: '取消扫描', exact: true }).click()
    await page.getByText('尚未扫描', { exact: true }).waitFor()
    await nav.getByRole('link', { name: '概览', exact: true }).click()
    await page.getByRole('link', { name: '1 项需要处理', exact: true }).click()
    await page.getByText('DEMO-003 · 森林清晨', { exact: true }).waitFor()
    assert.equal(await page.getByText('DEMO-001 · 山间旅程', { exact: true }).count(), 0)
    await page.getByRole('button', { name: '重试保存', exact: true }).click()
    await page.getByText('没有符合筛选条件的字幕任务', { exact: true }).waitFor()
    await page.getByRole('button', { name: '已完成与已取消' }).click()
    await page.getByText('已保存', { exact: true }).waitFor()
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false)
    await nav.getByRole('link', { name: '待确认', exact: true }).click()
    await page.getByRole('tablist', { name: '待确认分类' }).waitFor()
    await nav.getByRole('link', { name: '概览', exact: true }).click()
    await page.evaluate(() => { window.failTasks = true })
    await page.getByRole('button', { name: '刷新任务', exact: true }).click()
    await page.getByText('部分任务状态读取失败', { exact: false }).waitFor()
    await page.evaluate(() => { window.failTasks = false; window.emptyTasks() })
    await page.getByRole('button', { name: '刷新任务', exact: true }).click()
    await page.getByText('0 项运行中 · 5 项需处理', { exact: true }).waitFor()
    assert.deepEqual(errors, [])
    await page.close()
  }
  for (const viewport of [{ width: 1600, height: 1000 }, { width: 1000, height: 640 }, { width: 800, height: 640 }]) for (const theme of ['graphite', 'light']) {
    const page = await browser.newPage({ viewport, reducedMotion: 'reduce' }), errors = []
    page.on('pageerror', error => errors.push(error.message))
    await page.goto(`http://127.0.0.1:${server.httpServer.address().port}/task-center.html?theme=${theme}&scene=subtitles`)
    const saved = page.getByRole('region', { name: 'DEMO-071', exact: true })
    await saved.waitFor()
    await page.getByText('6 项任务', { exact: true }).waitFor()
    assert.equal(await page.getByRole('heading', { name: '影片播放', exact: true }).count(), 0)
    assert.equal(await page.getByRole('progressbar', { name: 'DEMO-001 · 山间旅程生成进度' }).getAttribute('value'), '42')
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false)
    if (viewport.width === 1600) await page.screenshot({ path: path.join(repo, `out/subtitle-tasks-redesign-${theme}.png`) })
    if (viewport.width === 1000 && theme === 'graphite') await page.screenshot({ path: path.join(repo, 'out/subtitle-tasks-redesign-compact.png') })
    const more = saved.getByRole('button', { name: 'DEMO-071更多操作' })
    await more.click()
    await page.getByRole('menuitem', { name: '另存／替换' }).waitFor()
    await page.keyboard.press('Escape')
    assert.equal(await more.evaluate(element => element === document.activeElement), true)
    await more.click()
    await page.getByRole('menuitem', { name: '查看详情', exact: true }).waitFor()
    await page.waitForFunction(() => document.activeElement?.textContent === '查看详情')
    await page.keyboard.press('End')
    assert.equal(await page.getByRole('menuitem', { name: '移除任务', exact: true }).evaluate(element => element === document.activeElement), true)
    await page.keyboard.press('Enter')
    await saved.getByRole('group', { name: '确认字幕操作' }).waitFor()
    assert.equal(await page.evaluate(() => window.taskCommands.includes('remove')), false, 'menu only requests confirmation')
    await saved.getByRole('button', { name: '返回', exact: true }).click()
    await more.click()
    await page.getByRole('menuitem', { name: '导出 SRT', exact: true }).click()
    assert.deepEqual(await page.evaluate(() => window.taskCommandDetails.at(-1)), { action: 'export-srt', id: 'completed' })
    const failed = page.getByRole('region', { name: 'DEMO-059', exact: true })
    await failed.getByRole('button', { name: '查看详情', exact: true }).click()
    await failed.getByText('问题详情', { exact: true }).waitFor()
    await page.evaluate(() => { window.failCommand = 'resume' })
    await failed.getByRole('button', { name: '继续', exact: true }).click()
    await failed.getByRole('alert').waitFor()
    assert.equal(await saved.getByRole('alert').count(), 0, 'command failure stays attached to its task')
    await page.getByRole('button', { name: '进行中与已暂停', exact: true }).click()
    await failed.waitFor({ state: 'detached' })
    assert.equal(await page.getByRole('region', { name: 'DEMO-004', exact: true }).count(), 1)
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false)
    assert.deepEqual(errors, [])
    await page.close()
  }
  console.log('Task center: 3 sizes × 2 themes; overview counts, category routing, batch controls, scan cancellation, subtitle save/filter, pending workbench and error recovery passed (synthetic RPC).')
  console.log('Subtitle redesign: 3 sizes × 2 themes; filename fallback, progress, filters, menu keyboard/focus, row-local confirmation, export target and scoped failures passed.')
} finally {
  await browser?.close(); await server?.close()
  if (path.dirname(temporary) !== path.resolve(os.tmpdir())) throw new Error('Unexpected fixture directory')
  await fs.rm(temporary, { recursive: true, force: true })
}
