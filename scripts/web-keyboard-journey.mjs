import assert from 'node:assert/strict'

// Only keyboard events perform UI actions. DOM access below is observation only.
export async function tabTo(page, selector, key = 'Tab', limit = 180) {
  for (let steps = 0; steps < limit; steps++) {
    if (await page.evaluate(selector => document.activeElement?.matches(selector), selector)) return steps
    await page.keyboard.press(key)
  }
  throw new Error(`Keyboard cannot reach ${selector}`)
}

export async function keyboardJourney(page) {
  await page.keyboard.press('/')
  assert.equal(await page.evaluate(() => document.activeElement?.id), 'web-search')
  const searchSteps = 1
  await page.keyboard.type('sample')
  await page.keyboard.press('Enter')
  await page.waitForFunction(() => document.activeElement?.matches('[data-browse-results] [data-web-video-card]'))
  await page.keyboard.press('ArrowRight')
  await page.keyboard.press('ArrowDown')
  await page.keyboard.press('Enter')
  await page.locator('[data-web-detail] h1').waitFor()
  assert.equal(await page.evaluate(() => document.activeElement?.id), 'detail-back')
  await page.keyboard.press('ArrowDown')
  assert.equal(await page.evaluate(() => document.activeElement?.tagName), 'VIDEO')
  await page.waitForFunction(() => document.querySelector('video')?.readyState >= 1)
  await page.keyboard.press('Space')
  await page.waitForFunction(() => !document.querySelector('video').paused)
  await page.keyboard.press('Space')
  await page.waitForFunction(() => document.querySelector('video').paused)
  const beforeSeek = await page.locator('video').evaluate(video => video.currentTime)
  await page.keyboard.press('ArrowRight')
  await page.waitForFunction(before => document.querySelector('video').currentTime > before, beforeSeek)
  await page.keyboard.press('ArrowUp')
  assert.notEqual(await page.evaluate(() => document.activeElement?.tagName), 'VIDEO')
  const actorSteps = await tabTo(page, '[data-web-cast-member]')
  await page.keyboard.press('Enter')
  await page.waitForURL('**/*actress=1*')
  await page.waitForFunction(() => document.activeElement?.matches('[data-browse-results] [data-web-video-card]'))
  await tabTo(page, '[data-web-sort] button:last-child', 'Shift+Tab')
  await page.keyboard.press('Enter')
  await page.waitForURL('**/*sort=code*')
  await page.waitForFunction(() => document.activeElement?.matches('[data-browse-results] [data-web-video-card]'))
  const chipSteps = await tabTo(page, '[data-web-filter-chips] button:last-child', 'Shift+Tab')
  await page.keyboard.press('Enter')
  await page.waitForFunction(() => !location.hash.includes('actress='))
  await page.waitForFunction(() => document.activeElement?.matches('[data-browse-results] [data-web-video-card]'))
  const pageSteps = await tabTo(page, '[data-web-pagination] button:last-child')
  await page.keyboard.press('Enter')
  await page.waitForURL('**/*page=2*')
  await page.waitForFunction(() => document.activeElement?.matches('[data-browse-results] [data-web-video-card]'))
  await page.keyboard.press('Enter')
  await page.locator('[data-web-detail] h1').waitFor()
  await page.keyboard.press('Escape')
  await page.waitForFunction(() => document.activeElement?.matches('[data-browse-results] [data-web-video-card]'))
  await tabTo(page, 'header[data-navigation-region=header] a')
  await page.keyboard.press('Shift+Tab')
  assert.equal(await page.evaluate(() => document.activeElement?.hasAttribute('data-web-skip')), true)
  await page.keyboard.press('Tab')
  assert.equal(await page.evaluate(() => document.activeElement?.matches('header[data-navigation-region=header] a')), true)
  await page.keyboard.press('ArrowUp')
  assert.equal(await page.evaluate(() => document.activeElement?.hasAttribute('data-web-skip')), false)
  await tabTo(page, 'header[data-navigation-region=header] a')
  await page.keyboard.press('Enter')
  await page.getByRole('heading', { name: '随机发现', exact: true }).waitFor()
  await tabTo(page, '[data-web-home-heading] button')
  await page.keyboard.press('Enter')
  await page.waitForFunction(() => document.querySelector('[data-web-home-heading] button').getAttribute('aria-disabled') === 'false')
  assert.equal(await page.evaluate(() => document.activeElement?.matches('[data-web-home-heading] button')), true)
  console.log('KEYBOARD journey', { searchSteps, actorSteps, chipSteps, pageSteps })
}
